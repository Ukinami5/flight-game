// Bundle our source modules for direct file:// use; HTTP uses the original ES modules.
// The vendored Three.js file itself is never modified.
import { readFileSync, writeFileSync } from 'node:fs';
const vendor=readFileSync('game/vendor/three.module.min.js','utf8');
const match=vendor.match(/export\s*\{([^}]+)\}\s*;?\s*$/);
if(!match)throw new Error('Three.js export table not found');
const exports=match[1].split(',').map(part=>{const [local,name]=part.trim().split(/\s+as\s+/);return JSON.stringify(name||local)+':'+local;}).join(',');
let output='// Generated by build-offline.mjs. Edit the source ES modules, then rebuild.\n(()=>{\n"use strict";\nconst THREE=(()=>{\n'+vendor.slice(0,match.index)+'\nreturn {'+exports+'};})();\n';
for(const file of ['random','world','aircraft','cockpit','input','audio','hud','shots','main']){
  let source=readFileSync('game/src/'+file+'.js','utf8');
  source=source.replace(/^import\s.*?;\s*$/gm,'').replace(/^export /gm,'');
  output+='\n// '+file+'.js\n'+source+'\n';
}
writeFileSync('game/src/offline.js',output+'\n})();\n');
console.log('Built offline bundle: '+(output.length+6)+' bytes');
